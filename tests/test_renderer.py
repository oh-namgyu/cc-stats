"""Page tests: the dashboard must be complete, self-contained and inert."""

import re
import unittest

from cc_stats import __version__
from cc_stats.aggregator import Metrics
from cc_stats.renderer import date_range, render, tiles
from cc_stats.scanner import ScanStats
try:  # discovery puts tests/ on the path; a package import also works
    from test_svg_charts import demo_metrics, tokens
except ImportError:  # pragma: no cover
    from tests.test_svg_charts import demo_metrics, tokens


class PageTestCase(unittest.TestCase):
    def test_document_shell(self):
        page = render(demo_metrics())
        self.assertTrue(page.lstrip().startswith("<!DOCTYPE html>"))
        self.assertIn("</html>", page)
        self.assertNotIn("%%", page)
        self.assertIn("<title>cc-stats &middot; 2026-01-01 to 2026-01-02</title>", page)

    def test_page_has_no_javascript_at_all(self):
        page = render(demo_metrics())
        for banned in ("<script", "javascript:", "onclick", "onload", "onerror"):
            self.assertNotIn(banned, page)

    def test_no_external_resources(self):
        page = render(demo_metrics())
        # The only URL-shaped attribute is the inlined data: favicon.
        icon = re.search(r'<link rel="icon"[^>]*>', page)
        self.assertIsNotNone(icon)
        self.assertIn('href="data:image/png;base64,', icon.group(0))
        body = page.replace(icon.group(0), "")
        for banned in ("http://", "https://", "//cdn", "@import", "url("):
            self.assertNotIn(banned, body)
        for value in re.findall(r'\bsrc\s*=\s*"([^"]*)"', page):
            self.fail("unexpected external resource: " + value)

    def test_every_chart_is_embedded(self):
        page = render(demo_metrics())
        self.assertEqual(page.count('<svg class="chart"'), 7)
        self.assertEqual(page.count('<article class="card'), 7)
        self.assertEqual(page.count('class="card wide"'), 4)

    def test_summary_tiles(self):
        page = render(demo_metrics())
        for expected in ("<b>3</b><span>sessions</span>",
                         "<b>7</b><span>turns</span>",
                         "<b>9</b><span>tool calls</span>",
                         "<b>100</b><span>tokens in</span>",
                         "<b>200</b><span>tokens out</span>",
                         "<b>20.0%</b><span>tool error rate</span>"):
            self.assertIn(expected, page)
        self.assertIn("2026-01-01 to 2026-01-02", page)

    def test_skipped_tile_appears_only_when_files_were_skipped(self):
        self.assertIn("files skipped", tiles(demo_metrics()))
        clean = demo_metrics(scan=ScanStats(found=3, included=3, skipped=0))
        self.assertNotIn("files skipped", tiles(clean))
        self.assertNotIn("tile warn", tiles(clean))

    def test_footer_reports_version_and_generation_time(self):
        page = render(demo_metrics())
        self.assertIn("Generated by cc-stats %s" % __version__, page)
        self.assertRegex(page, r"\d{4}-\d{2}-\d{2} \d{2}:\d{2} UTC")

    def test_footer_lists_ignored_duplicates_when_present(self):
        noisy = demo_metrics(warnings={"idless": 2, "duplicate_tool_use": 5,
                                       "duplicate_tool_result": 0,
                                       "malformed_lines": 0})
        page = render(noisy)
        self.assertIn("ignored:", page)
        self.assertIn("5 duplicate tool use", page)
        self.assertIn("2 idless", page)
        self.assertNotIn("0 malformed lines", page)

    def test_empty_metrics_render_a_valid_page(self):
        page = render(Metrics(heatmap=[[0] * 24 for _ in range(7)]))
        self.assertTrue(page.lstrip().startswith("<!DOCTYPE html>"))
        self.assertNotIn("%%", page)
        self.assertIn("No data yet", page)
        self.assertIn("no activity", page)
        self.assertEqual(page.count('<svg class="chart"'), 7)

    def test_date_range_helper(self):
        self.assertEqual(date_range(demo_metrics()), ("2026-01-01", "2026-01-02"))
        self.assertEqual(date_range(Metrics()), (None, None))

    def test_hostile_project_and_tool_names_are_inert(self):
        nasty = '<script>alert(1)</script>"><img src=x>'
        page = render(demo_metrics(
            tools={nasty: 4},
            projects={nasty: dict(tokens(1, 2, 3, 4), sessions=1)}))
        self.assertNotIn("<script", page)
        self.assertNotIn("<img", page)
        self.assertIn("&lt;script&gt;", page)

    def test_long_project_names_do_not_widen_the_page(self):
        wide = "-Users-someone-" + "y" * 200
        page = render(demo_metrics(
            projects={wide: dict(tokens(1, 2, 3, 4), sessions=1)}))
        self.assertNotIn(wide, page.split("<title>")[1])
        self.assertIn("…", page)


if __name__ == "__main__":
    unittest.main()
