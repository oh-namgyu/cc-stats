"""Assemble aggregated metrics into one self-contained HTML dashboard."""

from datetime import datetime, timezone
from typing import Dict, List, Optional, Tuple

from . import __version__
from .aggregator import Metrics
from .labels import pretty
from .svg_charts import (cache_chart, errors_chart, esc, heatmap_chart, projects_chart,
                         sessions_chart, tokens_chart, tools_chart)
from .template import CSS, FAVICON, TEMPLATE_HTML


def _fill(template: str, values: Dict[str, str]) -> str:
    """Replace ``%%KEY%%`` placeholders in a single left-to-right pass."""
    out = []  # type: List[str]
    cursor = 0
    while True:
        start = template.find("%%", cursor)
        if start < 0:
            break
        end = template.find("%%", start + 2)
        if end < 0:
            break
        key = template[start + 2:end]
        if key in values:
            out.append(template[cursor:start])
            out.append(values[key])
            cursor = end + 2
        else:
            out.append(template[cursor:start + 2])
            cursor = start + 2
    out.append(template[cursor:])
    return "".join(out)


def _count(value: float) -> str:
    return "{:,}".format(int(value))


def date_range(metrics: Metrics) -> Tuple[Optional[str], Optional[str]]:
    days = sorted(metrics.daily_tokens)
    if not days:
        return None, None
    return days[0], days[-1]


def _tile(value: str, caption: str, warn: bool = False, wide: bool = False) -> str:
    extra = (" warn" if warn else "") + (" span2" if wide else "")
    return ('<div class="tile%s"><b>%s</b><span>%s</span></div>'
            % (extra, esc(value), esc(caption)))


def tiles(metrics: Metrics) -> str:
    """Summary row. The skipped-files tile appears only when something failed."""
    first, last = date_range(metrics)
    span = "%s to %s" % (first, last) if first else "no activity"
    tool_calls = sum(metrics.tools.values())
    parts = [
        _tile(_count(metrics.sessions), "sessions"),
        _tile(_count(metrics.turns), "turns"),
        _tile(_count(tool_calls), "tool calls"),
        _tile(_count(metrics.tokens.get("input", 0)), "tokens in"),
        _tile(_count(metrics.tokens.get("output", 0)), "tokens out"),
        _tile("%.1f%%" % (metrics.error_rate * 100), "tool error rate"),
        _tile(span, "date range", wide=True),
    ]
    if metrics.scan.skipped:
        parts.append(_tile(_count(metrics.scan.skipped), "files skipped", warn=True))
    return "".join(parts)


def _card(title: str, note: str, chart: str, wide: bool = False) -> str:
    return ('<article class="card%s"><h2>%s</h2><p>%s</p>%s</article>'
            % (" wide" if wide else "", esc(title), esc(note), chart))


def cards(metrics: Metrics, redact: bool = True) -> str:
    """Every chart card, in reading order."""
    def label_for(name: str) -> str:
        return pretty(name, metrics.project_paths.get(name), redact)

    return "".join([
        _card("Daily tokens",
              "Stacked by day. Input is small next to output because most of "
              "the prompt is served from cache.", tokens_chart(metrics), wide=True),
        _card("Daily cache tokens",
              "Cache traffic dwarfs input and output, so it has its own scale.",
              cache_chart(metrics)),
        _card("Tool error rate", "Days with no completed calls leave a gap.",
              errors_chart(metrics)),
        _card("Tool distribution", "Top %d tools by call count." % 12,
              tools_chart(metrics), wide=True),
        _card("Sessions per project", "Token totals shown alongside.",
              projects_chart(metrics, label_for), wide=True),
        _card("Activity by weekday and hour", "Local time. Hover a cell for the count.",
              heatmap_chart(metrics), wide=True),
        _card("Session length", "Minutes from first to last event.",
              sessions_chart(metrics)),
    ])


def crumbs(metrics: Metrics) -> str:
    first, last = date_range(metrics)
    scan = metrics.scan
    items = [
        "%s projects" % _count(len(metrics.projects)),
        "%s of %s transcripts read" % (_count(scan.included), _count(scan.found)),
        "%s active days" % _count(len(metrics.daily_tokens)),
    ]
    if first:
        items.insert(0, "%s to %s" % (first, last))
    return "".join("<span>%s</span>" % esc(item) for item in items)


def footer(metrics: Metrics) -> str:
    generated = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    warnings = metrics.warnings
    noisy = ", ".join("%s %s" % (_count(count), name.replace("_", " "))
                      for name, count in sorted(warnings.items()) if count)
    items = ["Generated by cc-stats %s" % __version__, generated,
             "%s assistant messages" % _count(metrics.assistant_messages)]
    if noisy:
        items.append("ignored: " + noisy)
    return "".join("<span>%s</span>" % esc(item) for item in items)


def render(metrics: Metrics, redact: bool = True) -> str:
    """Build the complete, self-contained HTML dashboard."""
    first, last = date_range(metrics)
    title = ("%s to %s" % (first, last)) if first else "no activity"
    return _fill(TEMPLATE_HTML, {
        "CSS": CSS,
        "FAVICON": FAVICON,
        "VERSION": esc(__version__),
        "TITLE": esc(title),
        "CRUMBS": crumbs(metrics),
        "TILES": tiles(metrics),
        "CARDS": cards(metrics, redact),
        "FOOTER": footer(metrics),
    })
